#!/usr/bin/env bash
# Writes THIRD-PARTY-NOTICES.txt: every third-party component shipped in the
# macOS app or the Windows zip, with licence texts.
#   scripts/notices.sh [OUT]   (default: THIRD-PARTY-NOTICES.txt at the repo root)
# The packaging scripts call this so each artifact carries notices for exactly
# what it was built from; `mise run notices` refreshes the committed copy.
# Needs: cargo-about (mise) and the vendor/longcable submodule.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="${1:-$ROOT/THIRD-PARTY-NOTICES.txt}"
cd "$ROOT"

# mise's rust tool puts ~/.cargo/bin first on PATH, where an older
# cargo-about may live; use the pinned one.
CARGO_ABOUT="$(mise where github:EmbarkStudios/cargo-about 2>/dev/null)/cargo-about"
[[ -x "$CARGO_ABOUT" ]] || CARGO_ABOUT="$(command -v cargo-about)"

git submodule update --init vendor/longcable >/dev/null
LC_REV="$(git -C vendor/longcable rev-parse HEAD)"
LC_DESC="$(git -C vendor/longcable describe --tags --always 2>/dev/null || echo "$LC_REV")"

RUST_CRATES="$(mktemp -t tightwire-about)"
trap 'rm -f "$RUST_CRATES"' EXIT
"$CARGO_ABOUT" generate --locked --manifest-path receiver/Cargo.toml \
  --config receiver/about.toml receiver/about.hbs -o "$RUST_CRATES" 2>/dev/null

rule() { printf '%s\n' "=============================================================================="; }

{
  cat <<EOF
Tightwire third-party notices
=============================

Tightwire is free software under the GNU General Public License, version 3 or
(at your option) any later version; the full text is in LICENSE. It includes
or is built with the components below, each under its own licence. All of
them are compatible with GPL-3.0-or-later.

  macOS app (Tightwire.app)
    - Longcable ${LC_DESC} (GPL-3.0-or-later), separate helper program
  Windows receiver (tightwire.exe)
    - Rust standard library (MIT OR Apache-2.0)
    - the Rust crates listed in section 2
    - the C runtime of the toolchain it was linked with (MSVC or MinGW-w64);
      these are system libraries in the sense of GPL-3.0 section 1

Trademarks: Elgato, Stream Deck, Wave Link and Corsair are trademarks of
their respective owners. Tightwire is an independent project, not affiliated
with or endorsed by Corsair or Elgato; product names are used only to
describe compatibility.

EOF
  rule
  cat <<EOF
1. Longcable
EOF
  rule
  cat <<EOF

Longcable, a USB/IP server for macOS.
Copyright 2026 Denis Arnst (Sapd), https://github.com/Sapd
Licence: GPL-3.0-or-later (the same text as Tightwire's LICENSE).

The macOS app contains Longcable's longcable-server program and its install
scripts, built unmodified from commit
  ${LC_REV}
of https://github.com/Sapd/longcable. It is a separate program that
Tightwire starts as its own process; no Longcable code is linked into
Tightwire.

Corresponding source: the vendor/longcable git submodule of the Tightwire
repository, https://github.com/thesammykins/tightwire, pinned to that
commit (git clone --recurse-submodules fetches it).

EOF
  rule
  echo "2. Rust crates in the Windows receiver"
  rule
  echo
  echo "Generated by cargo-about from receiver/Cargo.lock for x86_64-pc-windows-*."
  echo "Licences in use:"
  cat "$RUST_CRATES"
  echo
  rule
  echo "3. Rust standard library"
  rule
  cat <<'EOF'

The Rust standard library is statically linked into tightwire.exe.
Copyright (c) The Rust Project Developers. Licence: MIT OR Apache-2.0; the
MIT text is reproduced in section 2, and the source is at
https://github.com/rust-lang/rust.
EOF
} >"$OUT"
echo "wrote $OUT ($(wc -l <"$OUT" | tr -d ' ') lines)"
